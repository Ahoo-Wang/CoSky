package me.ahoo.cosky.api.openapi

import com.google.protobuf.Descriptors.Descriptor
import com.google.protobuf.Descriptors.EnumDescriptor
import com.google.protobuf.Descriptors.FieldDescriptor
import me.ahoo.cosky.api.v1.ErrorsProto
import me.ahoo.cosky.api.v1.LeasesProto
import me.ahoo.cosky.api.v1.ResourceProto
import me.ahoo.cosky.api.v1.ResourcesProto
import me.ahoo.cosky.api.v1.ViewsProto
import me.ahoo.cosky.api.v1.WatchProto
import me.ahoo.test.asserts.assert
import org.junit.jupiter.api.Test
import org.yaml.snakeyaml.LoaderOptions
import org.yaml.snakeyaml.Yaml
import org.yaml.snakeyaml.constructor.SafeConstructor
import java.io.File

/**
 * Checks build/openapi/cosky.yaml (generated by the build) against the protos and design §4.5.
 */
@Suppress("UNCHECKED_CAST")
class OpenApiDocumentTest {
    private val document: Map<String, Any> = File(System.getProperty("cosky.openapi")).reader().use {
        Yaml(SafeConstructor(LoaderOptions())).load<Map<String, Any>>(it)
    }
    private val schemas = (document["components"] as Map<String, Any>)["schemas"] as Map<String, Map<String, Any>>
    private val paths = document["paths"] as Map<String, Map<String, Any>>

    private val files = listOf(
        ResourceProto.getDescriptor(),
        ResourcesProto.getDescriptor(),
        WatchProto.getDescriptor(),
        LeasesProto.getDescriptor(),
        ViewsProto.getDescriptor(),
        ErrorsProto.getDescriptor(),
    )

    private fun messages(): List<Descriptor> {
        fun walk(message: Descriptor): List<Descriptor> =
            if (message.options.mapEntry) emptyList() else listOf(message) + message.nestedTypes.flatMap(::walk)
        return files.flatMap { it.messageTypes }.flatMap(::walk)
    }

    private fun enums(): List<EnumDescriptor> =
        files.flatMap { it.enumTypes } + messages().flatMap { it.enumTypes }

    private fun schemaName(fullName: String) = fullName.removePrefix("cosky.v1.")

    @Test
    fun `every proto message has a schema with every field under its JSON name`() {
        messages().forEach { message ->
            val schema = schemas.getValue(schemaName(message.fullName))
            val properties = (schema["properties"] as Map<String, Any>?).orEmpty()
            properties.keys.assert().containsExactlyElementsOf(message.fields.map(FieldDescriptor::getJsonName))
        }
    }

    @Test
    fun `every proto enum lists its value names`() {
        enums().forEach { enum ->
            schemas.getValue(schemaName(enum.fullName))["enum"].assert()
                .isEqualTo(enum.values.map { it.name })
        }
    }

    @Test
    fun `fields follow the proto3 JSON mapping`() {
        val meta = schemas.getValue("ObjectMeta")["properties"] as Map<String, Map<String, Any>>
        meta.getValue("revision").assert().isEqualTo(
            mapOf(
                "type" to "string",
                "format" to "int64",
                "description" to
                    meta.getValue("revision")["description"]
            ),
        )
        meta.getValue("createdAt")["format"].assert().isEqualTo("date-time")
        meta.getValue("labels")["type"].assert().isEqualTo("object")
        val instance = schemas.getValue("InstanceSpec")["properties"] as Map<String, Map<String, Any>>
        instance.getValue("weight")["format"].assert().isEqualTo("int32")
        val rule = schemas.getValue("Rule")["properties"] as Map<String, Map<String, Any>>
        rule.getValue(
            "kinds"
        ).assert().isEqualTo(mapOf("type" to "array", "items" to mapOf("\$ref" to "#/components/schemas/Kind")))
    }

    @Test
    fun `every design route is documented`() {
        val expected = mapOf(
            "/v1/namespaces/{namespace}/configs" to setOf("get"),
            "/v1/namespaces/{namespace}/configs/{name}" to setOf("get", "put", "delete"),
            "/v1/namespaces/{namespace}/configs/{name}/history" to setOf("get"),
            "/v1/namespaces/{namespace}/configs/{name}:rollback" to setOf("post"),
            "/v1/namespaces/{namespace}/configs:import" to setOf("post"),
            "/v1/namespaces/{namespace}/configs:export" to setOf("get"),
            "/v1/namespaces/{namespace}/instances" to setOf("get"),
            "/v1/namespaces/{namespace}/instances/{name}" to setOf("get", "put", "delete"),
            "/v1/namespaces/{namespace}/watch" to setOf("get"),
            "/v1/namespaces/{namespace}/views/services" to setOf("get"),
            "/v1/namespaces/{namespace}/views/topology" to setOf("get"),
            "/v1/namespaces/{namespace}/views/stats" to setOf("get"),
            "/v1/namespaces" to setOf("get"),
            "/v1/namespaces/{name}" to setOf("get", "put", "delete"),
            "/v1/serviceaccounts" to setOf("get"),
            "/v1/serviceaccounts/{name}" to setOf("get", "put", "delete"),
            "/v1/serviceaccounts/{name}/tokens" to setOf("post"),
            "/v1/serviceaccounts/{name}/tokens/{tokenId}" to setOf("delete"),
            "/v1/roles" to setOf("get"),
            "/v1/roles/{name}" to setOf("get", "put", "delete"),
            "/v1/rolebindings" to setOf("get"),
            "/v1/rolebindings/{name}" to setOf("get", "put", "delete"),
            "/v1/me" to setOf("get"),
        )
        paths.keys.assert().containsExactlyInAnyOrderElementsOf(expected.keys)
        expected.forEach { (path, methods) ->
            paths.getValue(
                path
            ).keys.filter { it != "parameters" }.assert().containsExactlyInAnyOrderElementsOf(methods)
        }
    }

    @Test
    fun `operation ids are unique`() {
        val ids = paths.values.flatMap { item ->
            item.filterKeys { it != "parameters" }.values.map { (it as Map<String, Any>)["operationId"] }
        }
        ids.assert().doesNotHaveDuplicates().doesNotContainNull()
    }

    @Test
    fun `watch is a server-sent event stream of WatchResponse`() {
        val get = paths.getValue("/v1/namespaces/{namespace}/watch")["get"] as Map<String, Any>
        val ok = (get["responses"] as Map<String, Map<String, Any>>).getValue("200")
        val content = ok["content"] as Map<String, Map<String, Any>>
        content.getValue("text/event-stream")["itemSchema"].assert()
            .isEqualTo(mapOf("\$ref" to "#/components/schemas/WatchResponse"))
    }

    @Test
    fun `writes take If-Match and creates If-None-Match`() {
        val put = paths.getValue("/v1/namespaces/{namespace}/configs/{name}")["put"] as Map<String, Any>
        (put["parameters"] as List<Map<String, Any>>).map { it["\$ref"] }.assert().containsExactly(
            "#/components/parameters/ifMatch",
            "#/components/parameters/ifNoneMatch",
        )
    }
}
